  <div class="col-md-4" data-for="indicator"><label class="form-label" for="period">Reporting period</label>
    <select class="form-select" id="period" name="period"><?= simple_options($periods, $f['period'], 'Latest recorded') ?></select></div>
  <div class="col-md-3" data-for="activity beneficiary"><label class="form-label" for="from">From date</label><input class="form-control" type="date" id="from" name="from" value="<?= e($f['from']) ?>"></div>
  <div class="col-md-3" data-for="activity beneficiary"><label class="form-label" for="to">To date</label><input class="form-control" type="date" id="to" name="to" value="<?= e($f['to']) ?>"></div>
