/**
 * A small PDF writer for report tables (A4 landscape, Helvetica), so reports can be downloaded
 * as real PDF files without installing any library. The naira sign is written as "NGN" because
 * the standard PDF fonts do not contain it.
 */
function pdf_text(string $s): string
{
    $s = str_replace('(₦)', '(NGN)', $s);
    $s = str_replace(['₦', '–', '—', '’', '‘', '“', '”', '…', '÷', '×'], ['NGN ', '-', '-', "'", "'", '"', '"', '...', '/', 'x'], $s);
    $s = @iconv('UTF-8', 'windows-1252//TRANSLIT//IGNORE', $s) ?: preg_replace('/[^\x20-\x7E]/', '?', $s);
    return str_replace(['\\', '(', ')', "\r", "\n"], ['\\\\', '\\(', '\\)', '', ' '], $s);
}

function pdf_wrap(string $text, float $width, float $size): array
{
    $max = max(1, (int) floor($width / ($size * 0.5)));
    $lines = []; $line = '';
    foreach (preg_split('/\s+/', trim($text)) as $word) {
        while (mb_strlen($word) > $max) { if ($line !== '') { $lines[] = $line; $line = ''; } $lines[] = mb_substr($word, 0, $max); $word = mb_substr($word, $max); }
        if ($line === '') { $line = $word; }
        elseif (mb_strlen($line . ' ' . $word) <= $max) { $line .= ' ' . $word; }
        else { $lines[] = $line; $line = $word; }
    }
    $lines[] = $line;
    return $lines;
}

function report_pdf_bytes(array $report): string
{
    $W = 842; $H = 595; $m = 36; $usable = $W - 2 * $m; $fs = 8.0; $lead = 10.0;
    $cols = $report['columns']; $n = count($cols);
    $len = array_fill(0, $n, 6);
    foreach (array_merge([$cols], $report['rows']) as $r) { foreach (array_values($r) as $i => $c) { $len[$i] = max($len[$i], min(40, mb_strlen((string) (is_float($c) ? fmt_number($c) : $c)))); } }
    $sum = array_sum($len); $w = [];
    foreach ($len as $i => $l) { $w[$i] = max(34.0, $usable * $l / $sum); }
    $scale = $usable / array_sum($w); foreach ($w as $i => $v) { $w[$i] = $v * $scale; }

    $pages = []; $cur = ''; $y = $H - $m;
    $emit = function (string $s) use (&$cur) { $cur .= $s . "\n"; };
    $txt = function (float $x, float $yy, string $s, float $size, bool $bold = false) use ($emit) { $emit(sprintf('BT /%s %.1F Tf %.2F %.2F Td (%s) Tj ET', $bold ? 'F2' : 'F1', $size, $x, $yy, pdf_text($s))); };
    $newPage = function () use (&$pages, &$cur, &$y, $H, $m) { if ($cur !== '') { $pages[] = $cur; } $cur = ''; $y = $H - $m; };
    $header = function () use (&$y, $cols, $w, $m, $emit, $txt, $fs, $lead) {
        $hl = []; $hh = 1;
        foreach ($cols as $i => $c) { $hl[$i] = pdf_wrap((string) $c, $w[$i] - 4, $fs); $hh = max($hh, count($hl[$i])); }
        $emit(sprintf('0.88 0.90 0.94 rg %.2F %.2F %.2F %.2F re f 0 g', $m, $y - $hh * $lead - 2, array_sum($w), $hh * $lead + 4));
        $x = $m; foreach ($hl as $i => $lines) { foreach ($lines as $k => $line) { $txt($x + 2, $y - ($k + 1) * $lead + 3, $line, $fs, true); } $x += $w[$i]; }
        $y -= $hh * $lead + 6;
    };
    $txt($m, $y, $report['title'], 15, true); $y -= 16;
    $txt($m, $y, $report['filters'], 8.5); $y -= 11;
    $txt($m, $y, 'Generated by ' . $report['by'] . ' on ' . $report['generated'] . '   |   ' . cfg('app_name'), 8.5); $y -= 16;
    foreach (array_chunk($report['summary'], 3) as $chunk) {
        $x = $m; foreach ($chunk as [$label, $val]) { $txt($x, $y, $label . ': ' . (is_float($val) ? fmt_number($val) : $val), 9, true); $x += $usable / 3; }
        $y -= 12;
    }
    $y -= 8; $header();
    foreach ($report['rows'] as $r) {
        $cells = []; $h = 1;
        foreach (array_values($r) as $i => $c) { $cells[$i] = pdf_wrap((string) (is_float($c) ? fmt_number($c) : $c), $w[$i] - 4, $fs); $h = max($h, count($cells[$i])); }
        $rowH = $h * $lead + 3;
        if ($y - $rowH < $m + 14) { $newPage(); $header(); }
        $x = $m;
        foreach ($cells as $i => $lines) { foreach ($lines as $k => $line) { $txt($x + 2, $y - ($k + 1) * $lead + 3, $line, $fs); } $x += $w[$i]; }
        $y -= $rowH;
        $emit(sprintf('0.8 g %.2F %.2F %.2F 0.4 re f 0 g', $m, $y + 1, array_sum($w)));
    }
    if (!$report['rows']) { $txt($m, $y - 10, 'No records match these filters.', 9); }
    $pages[] = $cur;
    $total = count($pages);
    foreach ($pages as $i => &$p) { $p .= sprintf("BT /F1 8 Tf %.2F %.2F Td (%s) Tj ET\n", $W - $m - 60, 18, 'Page ' . ($i + 1) . ' of ' . $total); }
    unset($p);

    $objs = [1 => '<< /Type /Catalog /Pages 2 0 R >>', 3 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>', 4 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>'];
    $kids = []; $num = 5;
    foreach ($pages as $p) {
        $pg = $num++; $ct = $num++; $kids[] = "$pg 0 R";
        $objs[$pg] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 $W $H] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents $ct 0 R >>";
        $objs[$ct] = '<< /Length ' . strlen($p) . " >>\nstream\n" . $p . 'endstream';
    }
    $objs[2] = '<< /Type /Pages /Kids [' . implode(' ', $kids) . '] /Count ' . count($kids) . ' >>';
    ksort($objs);
    $pdf = "%PDF-1.4\n"; $off = [];
    foreach ($objs as $i => $body) { $off[$i] = strlen($pdf); $pdf .= "$i 0 obj\n$body\nendobj\n"; }
    $xref = strlen($pdf); $max = max(array_keys($objs));
    $pdf .= "xref\n0 " . ($max + 1) . "\n0000000000 65535 f \n";
    for ($i = 1; $i <= $max; $i++) { $pdf .= sprintf("%010d 00000 n \n", $off[$i] ?? 0); }
    return $pdf . "trailer\n<< /Size " . ($max + 1) . " /Root 1 0 R >>\nstartxref\n$xref\n%%EOF";
}

function send_report_pdf(array $report, string $baseName): void
{
    $bytes = report_pdf_bytes($report);
    header('Content-Type: application/pdf');
    header('Content-Disposition: attachment; filename="' . $baseName . '.pdf"');
    header('Content-Length: ' . strlen($bytes));
    echo $bytes;
}
